package com.reedobook.controller; // Ensure this matches your actual package

import com.reedobook.entity.Semester; // Import the Semester entity
import com.reedobook.service.SemesterService; // Import the SemesterService
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus; // For HTTP status codes like CREATED, NOT_FOUND
import org.springframework.http.ResponseEntity; // To return custom HTTP responses
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.*; // Import all necessary Spring Web annotations

import java.util.List;
import java.util.Optional; // For handling Optional results from service/repository

@CrossOrigin(origins = "http://localhost:3000")
@RestController // Marks this class as a Spring REST Controller, handling web requests
@RequestMapping("/semester") // Base URL path for all API endpoints in this controller (e.g., /api/semesters/add)
public class SemesterController {

    private final SemesterService semesterService; // Inject SemesterService

    @Autowired // Spring will automatically inject an instance of SemesterService via constructor
    public SemesterController(SemesterService semesterService) {
        this.semesterService = semesterService;
    }

    // --- API Endpoints ---

    /**
     * 1. Add a New Semester
     * HTTP Method: POST
     * URL: /api/semesters/add
     * Request Body: JSON object containing "semester_name" and "course_id".
     * The "semester_id" must NOT be provided in the request body, as it's auto-generated by the database.
     *
     * Example Request Body:
     * {
     * "semester_name": "Spring 2025",
     * "course_id": 123 // This course_id MUST exist in your 'course' table!
     * }
     *
     * Successful Response: HTTP 201 Created with the saved Semester object.
     * Error Response:      HTTP 400 Bad Request with an error message (e.g., if semester_id is provided, or foreign key fails).
     */
    @PreAuthorize("hasRole('ADMIN')")
    @PostMapping("/addSemester")
    public ResponseEntity<?> addSemester(@RequestBody Semester semester) {
        try {
            // Validate that the client is not trying to set the auto-generated ID
            if (semester.getId() != null) {
                return ResponseEntity.badRequest().body("Semester ID should not be provided for a new semester; it is auto-generated by the system.");
            }

            // Call the service layer to save the semester to the database
            Semester savedSemester = semesterService.saveSemester(semester);

            // Return 201 Created status, which is appropriate for successful resource creation
            return ResponseEntity.status(HttpStatus.CREATED).body(savedSemester);
        } catch (Exception e) {
            // Catch any unexpected exceptions (e.g., Foreign Key Constraint failure if course_id doesn't exist)
            // and return a 400 Bad Request with a descriptive error message.
            return ResponseEntity.badRequest().body("Error adding semester: " + e.getMessage());
        }
    }

    @GetMapping("/getSemesterByCourseId/{courseId}")
    public ResponseEntity<?> getSemesterByCourseId(@PathVariable("courseId") Long courseId) {
        try {
            List<Semester> semester = semesterService.getSemesterByCourseId(courseId);
            if (semester.isEmpty()) {
                return ResponseEntity.noContent().build();
            }
            return ResponseEntity.ok(semester); // 200 OK
        } catch (Exception e) {
            return ResponseEntity.badRequest().body("Error fetching semester by ID: " + e.getMessage());
        }
    }

    /**
     * 3. Get Semester by ID
     * HTTP Method: GET
     * URL: /api/semesters/{semester_id}
     * Example: /api/semesters/1
     *
     * Successful Response: HTTP 200 OK with the Semester object.
     * Not Found Response:  HTTP 404 Not Found if the semester does not exist.
     * Error Response:      HTTP 400 Bad Request for other errors.
     */
    @GetMapping("/{semesterId}")
    public ResponseEntity<?> getSemesterById(@PathVariable("semesterId") Long semesterId) {
        try {
            Optional<Semester> semester = semesterService.getSemesterById(semesterId);
            if (semester.isPresent()) {
                return ResponseEntity.ok(semester.get()); // 200 OK
            } else {
                return ResponseEntity.status(HttpStatus.NOT_FOUND) // 404 Not Found
                        .body("Semester not found with ID: " + semesterId);
            }
        } catch (Exception e) {
            return ResponseEntity.badRequest().body("Error fetching semester by ID: " + e.getMessage());
        }
    }

    /**
     * 4. Update an Existing Semester
     * HTTP Method: PUT
     * URL: /api/semesters/{semester_id}
     * Request Body: JSON object containing the updated "semester_name" and "course_id".
     * The "semester_id" in the URL path specifies WHICH semester to update.
     *
     * Example Request Body (to update semester with ID 1):
     * {
     * "semester_name": "Summer 2025",
     * "course_id": 456 // Make sure this course_id exists!
     * }
     *
     * Successful Response: HTTP 200 OK with the updated Semester object.
     * Not Found Response:  HTTP 404 Not Found if the semester to update does not exist.
     * Error Response:      HTTP 400 Bad Request for other errors.
     */
    @PreAuthorize("hasRole('ADMIN')")
    @PutMapping("/{semesterId}")
    public ResponseEntity<?> updateSemester(@PathVariable("semesterId") Long semesterId, @RequestBody Semester semesterDetails) {
        try {
            Semester updatedSemester = semesterService.updateSemester(semesterId, semesterDetails);
            if (updatedSemester != null) {
                return ResponseEntity.ok(updatedSemester); // 200 OK
            } else {
                return ResponseEntity.status(HttpStatus.NOT_FOUND) // 404 Not Found
                        .body("Semester not found with ID: " + semesterId);
            }
        } catch (Exception e) {
            return ResponseEntity.badRequest().body("Error updating semester: " + e.getMessage());
        }
    }

    /**
     * 5. Delete a Semester
     * HTTP Method: DELETE
     * URL: /api/semesters/{semester_id}
     * Example: /api/semesters/1
     *
     * Successful Response: HTTP 204 No Content (standard for successful deletion)
     * Not Found Response:  HTTP 404 Not Found if the semester to delete does not exist.
     * Error Response:      HTTP 400 Bad Request for other errors.
     */
    @PreAuthorize("hasRole('ADMIN')")
    @DeleteMapping("/{semesterId}")
    public ResponseEntity<?> deleteSemester(@PathVariable("semesterId") Long semesterId) {
        try {
            boolean deleted = semesterService.deleteSemester(semesterId);
            if (deleted) {
                return ResponseEntity.noContent().build(); // 204 No Content
            } else {
                return ResponseEntity.status(HttpStatus.NOT_FOUND) // 404 Not Found
                        .body("Semester not found with ID: " + semesterId);
            }
        } catch (Exception e) {
            return ResponseEntity.badRequest().body("Error deleting semester: " + e.getMessage());
        }
    }
}